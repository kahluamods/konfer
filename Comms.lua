--[[
This file contains all of the functions for dealing with sending and receiving of inter-mod communications. It is where the
Konfer "protocol" is implemented. A few brief notes about how things work.

Almost all events center around looting and are generated by the master looter. Other maintenance events can be generated by
any admin, and a few are generated by normal users.

In general the person who sent the event has already done the work described by the event. For example, when the master
looter loots a boss or chest, they will send out the list of items to populate the loot window with. However, their own loot
list will already have been populated.

Events are always sent with an event name and the event data, to the whole guild or group, or whispered to one player. The
protocol version is sent with each message. A message from a higher version than ours is refused and tells us we are out of
date. Anything at or below ours is accepted. Receipts can be about any config the sender holds, and the message handlers must
act accordingly.

Every handler is given the policy a message arrived for, POL, beside the command and the config, and it is nil for the mod's
own. Nothing has to look it up and nothing has to carry it in its payload to find out.

mhandlers are the mod's, the ones named CMD_MOD: the bare DEBUG, CINFO and CIACK, GLASK and GLANS, and BCAST and CSYNC,
which carry their configs in their payloads. The mod sends them with its own SendAM and friends, and having no current config of its own, it
sends them without one.

CINFO and CIACK are the character info check and reply and lives in CharInfo.lua.

ihandlers and ehandlers are the standard event set: what a policy accepts unless it says otherwise. RegisterPolicy gives
every policy its own copy of both, so a policy's Comms.lua adds to, replaces or removes entries in its own tables without
touching anybody else's. Suicide Kings adds SULST and SUNDO to its copy; EP/GP will never have heard of them. They arrive
named by the policy that sent them.

The two differ in weight rather than in ownership. An ihandler is immediate traffic, live during a raid, recorded nowhere. An
ehandler is part of the config's event stream: gated on being an admin, checked against the sender's last event id, and
folded into the running checksum.

Every command is five characters, in all three tables and in every policy that adds its own. Nothing enforces it and nothing
today would break if one were not, a command travelling as a value of its own and being read back as one rather than sliced
out of a wider string. Keep to it anyway. It is what makes a debug line or a sync queue readable at a glance, it keeps every
command the same width on the wire, and a mod that has held to one shape across every command it has ever had is worth not
being the first to break. A policy wanting a longer word should shorten it rather than widen the set.
]]

local mhandlers = {}
