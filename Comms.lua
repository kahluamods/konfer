--
-- Command: LHADD timestamp ilink who how listid pdata
-- Purpose: Sent when a master looter assigns loot through Konfer. This is sent to everybody holding the config, raiders as
--          well as admins, each keeping and trimming a history of their own, and is ignored where the config says it keeps
--          no history, that being a setting of the config's and the same for everybody rather than each one's own choice. A
--          raider who is no admin keeps it only where they asked to on the Options page (konfer.chardb.recordhistory).
--          Otherwise it adds the item to the loot history table for the configuration.
--
--          TIMESTAMP is when the loot was assigned, ILINK is what loot was assigned and WHO the userid it was assigned to.
--          HOW in upper case is one of the platform's ways: "D" disenchanted, "R" won on a roll, "M", "O", "T" and "V" a main
--          spec, off spec, transmog and vanity roll, "B" a BoE to the master looter, "A" auto-assigned and "U" an undo. In
--          lower case it is the policy's own, an award or an undo of one, and PDATA is whatever the policy's HistoryEntry
--          or HistoryUndo kept beside it.
--          LISTID is the list it was given out on, false for none.
--
ehandlers.LHADD = function(self, live, sender, proto, pol, cmd, cfg, ...)
  local when, what, who, how, listid, pdata = ...

  -- A raider keeps the history of a config they are no admin of only where they asked to (konfer.chardb.recordhistory).
  if (not cfg.settings.history or (not cfg:MyStatus() and not self.chardb.recordhistory)) then
    return
  end

  -- A batch redraws the history once when it is done.
  cfg:AddLootHistory(when, what, who, how, listid, pdata, not live, true)
end

--
-- Command: LHBCS rows
-- Purpose: The master looter sharing the config's loot history, ROWS every row of it laid out as konfer.HIST_* says, so
--          that everybody using the mod has what was handed out while they were not there to see it. The receiver keeps
--          what it has and adds each row it does not hold, its history being its own to keep and to trim
--          (cfg:TakeLootHistory). An admin takes it as a matter of course. Anybody else is asked first
--          (konfer:OfferLootHistory), unless they have said never (konfer.chardb.ignorehistory). Sent at most once every
--          konfer.HISTORY_BCAST_GAP seconds, by the History tab's Broadcast button.
--
ihandlers.LHBCS = function(self, sender, proto, pol, cmd, cfg, rows)
  if (type(rows) ~= "table" or not cfg.settings.history) then
    return
  end

  if (cfg:MyStatus()) then
    cfg:TakeLootHistory(rows)
  elseif (not self.chardb.ignorehistory) then
    self:OfferLootHistory(cfg, sender, rows)
  end
end

