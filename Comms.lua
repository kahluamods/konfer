  if (not llist) then
    return
  end

  -- Lists are sorted by comparing it, so one that is missing or not a number is 1, the first place there is.
  llist.sortorder = tonumber(sortorder) or 1
  llist.def_rank = tonumber(rank)
  llist.strictcfilter = stricta
  llist.strictrfilter = strictr
  llist.extralist = slist or "0"
  llist.tethered = tethered
  llist.altdisp = altdisp
