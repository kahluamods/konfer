--
-- Whether SENDER is an admin of config CFG, and whether they own it: 2 for the owner, 1 for a co-admin, nil for anybody
-- else. Some messages carry authority only from one or the other, and a flag the sender sets says nothing about who they are.
--
local function sender_admin(cfg, sender)
  local senduid = cfg:FindUser(sender)

  return senduid and cfg:IsAdmin(senduid) or nil
end

local function sent_by_owner(cfg, sender)
  return sender_admin(cfg, sender) == 2
end

--
-- The commands that name no config, and the whole of them. A recovery is asked for by name rather than by id, the owner
-- asking for one being the case where the two ends may hold it under different ids or the asker under none at all, so
-- these two carry the name in the payload and nothing in the envelope.
--
-- Everything else names one. That is enforced in policy_commdispatch rather than trusted, which is what lets every other
-- handler read its config without asking whether it has one.
--
local CONFIGLESS = {
  RCOVR = true,
  RCACK = true,
}

--
-- What has to be true of a message before its ihandler is called at all. A key that is not there is not a requirement, so
-- only `= true` gates anything and a command with no entry is unguarded.
--
-- CFG is the config itself and is never nil here, the dispatcher having refused a command that named none. The two that
-- name none deliberately have no entry, so they never reach a test.
--
--   need_active  that config is the active policy's current one
--   need_loot    there is loot up
--   need_ml      the sender is the one running loot
--   need_admin   the sender is an admin of the config
--
-- Only what can be answered from the message's envelope is here. Anything reading the message's own arguments stays in its
-- handler, as do the sync and recovery commands, whose tests are about who holds what rather than about whether to listen.
--
local REQUIRES = {
  OLOOT = { need_active = true, need_ml = true },
  CLOOT = { need_active = true, need_ml = true },
  ALOOT = { need_active = true, need_ml = true },
  LLSEL = { need_active = true, need_ml = true },
  BICAN = { need_active = true, need_ml = true },
  OROLL = { need_active = true, need_ml = true },
  EROLL = { need_active = true, need_ml = true },
  PROLL = { need_active = true, need_ml = true },
  RROLL = { need_active = true, need_ml = true },
  XROLL = { need_active = true, need_ml = true },
  TROLL = { need_active = true, need_ml = true },
  BIDCL = { need_active = true, need_loot = true, need_ml = true },
  LISEL = { need_active = true, need_loot = true, need_ml = true },
  BIREM = { need_active = true, need_loot = true, need_ml = true },
  FLTCH = { need_active = true, need_loot = true, need_ml = true },
  BIDOP = { need_active = true, need_loot = true, need_ml = true },
  BIDER = { need_active = true, need_loot = true, need_ml = true },
  XBIDS = { need_active = true, need_loot = true, need_ml = true },
  PBIDS = { need_active = true, need_loot = true, need_ml = true },

  -- A bid and a retraction come from the bidder, so neither is the master looter's to send.
  BIDME = { need_active = true, need_loot = true },
  BIDRT = { need_active = true, need_loot = true },

  -- Any admin may have added the users or said who is on reserve, neither being the master looter's business.
  RFUSR = { need_admin = true },
  RSUSR = { need_active = true, need_admin = true },

  -- The loot history is the config's, so only an admin of it may hand it round, whether or not it is the one loot runs on.
  LHBCS = { need_admin = true },

  REQRS = { need_active = true },
  ACKRS = { need_active = true },

  -- The Raid page's ticks are one selection among the config's admins, so only one of them changes it.
  RTICK = { need_active = true, need_admin = true },
}

--
-- Tested in this order, so a handler reading an argument off the config can rely on everything named before it. RSUSR's
-- own test of the uid it carries is the case that needs it.
--
local function requirements_met(self, sender, cmd, cfg)
  local req = REQUIRES[cmd]

  if (not req) then
    return true
  end

  local failed = (req.need_active and not cfg:IsActive() and "its config is not the active one")
    or (req.need_loot and not self.raid.bossloot and "there is no loot up")
    or (req.need_ml and not self:IsSenderMasterLooter(sender) and "the sender is not running loot")
    or (req.need_admin and not sender_admin(cfg, sender) and "the sender is no admin")

  if (failed) then
    self.debug(4, "%q from %q dropped: %s", cmd, sender, failed)
    return false
  end

  return true
end

--
-- The arguments of an event, from the encoded string it travels as, packed with their count, or nil for one that does not
-- decode or deserialise. What arrives from another client is never trusted to be well formed, and an error raised here
-- would be raised inside the comms callback.
--
local function pack(...)
  return { n = select("#", ...), ... }
end

local function event_args(estr)
  local decoded = estr and ZL:DecodeForWoWAddonChannel(estr)

  if (not decoded) then
    return nil
  end

  local res = pack(pcall(LS.DeserializeValue, LS, decoded))

  if (not res[1]) then
    return nil
  end

  return res
end

--
-- Full syncs this client has asked for, as config id -> { [name] = true }. A full sync replaces the whole config, so one
-- nobody asked for is not accepted. See cfg:RequestFullSync.
--
local fullsyncs_asked = {}

--
-- Ask NAME for a full sync of config CFGID, and remember having asked.
--
function cfgm:RequestFullSync(name)
  fullsyncs_asked[self.id] = fullsyncs_asked[self.id] or {}
  fullsyncs_asked[self.id][name] = true
  konfer:GetPolicy(self.id):CSendWhisperAM(self.id, name, "GSYNC", "ALERT", 0, true, 0, 0)
end

