--
-- Command: BIDOP idx timeout kinds amounts
-- Purpose: Opens bidding on the currently selected item. Recipients of this message merely need to activate their Bid on
--          item button in case the user is interested in bidding on the item. This is always preceeded by a BIDCL message
--          to clear the bid list just to be sure. Gets passed the index number of the item being bid on, which is currently
--          ignored as the item will have been set by LISEL. We could do an integrity check though. TIMEOUT is how many
--          seconds the bids stay open where they are timed, which every raider counts down, and 0 where they close when
--          the master looter says. KINDS is the kinds of bid this one takes, their codes run together ("MOT"),
--          which is what Bid on item offers whatever the recipient's own copy of the config says, and AMOUNTS whether a
--          bid names an amount, which puts the box it is typed in beside Bid on item. PRICE is what the master looter's
--          policy says the item costs (konfer:LootPrice), "75+" or "125", shown before it on the loot list, or false.
--
ihandlers.BIDOP = function(self, sender, proto, pol, cmd, cfg, ...)
  local idx, timeout, kinds, amounts, price = ...

  self:ResetBidders(false)
  self:OpenBid(idx, kinds, amounts and true or false, tonumber(timeout), type(price) == "string" and price or nil)
end

