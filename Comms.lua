--
-- Command: CHUSR uid flags main
-- Purpose: Sent to the raid / guild when what a user is in this config changes. UID is the user, FLAGS is every letter that
--          is now set, and MAIN is their main's uid when A is among them.
--
--          FLAGS is the whole of it rather than the letter that moved, so three changes are one event and a letter that is
--          not in it is a letter that is not set. That is what lets this clear the alt link: A missing is the sender saying
--          there is no main, which is a thing only this event ever says. See MDUSR below for why it cannot.
--
--          A letter a newer sender knows and this build does not is ignored, and everything it does know is still applied.
--
ehandlers.CHUSR = function(self, live, sender, proto, pol, cmd, cfg, ...)
  local uid, flags, main = ...

  -- An admin who is not yet syncing can be sent about a user they never received, just as anybody else can.
  if (not cfg.uids[uid] or type(flags) ~= "string") then
    return
  end

  cfg:SetUserEnchanter(uid, strfind(flags, "E", 1, true) ~= nil, true)
  cfg:SetUserFrozen(uid, strfind(flags, "F", 1, true) ~= nil, true)

  --
  -- Whose alt somebody is is not an opinion an admin can be honestly wrong about, the way a class or a profession is, so it
  -- is written as it stands rather than put to the player. MAIN is their main's uid in this config.
  --
  local isalt = strfind(flags, "A", 1, true) ~= nil

  cfg:SetUserIsAlt(uid, isalt, main, true)

  -- Redrawn in whichever window shows this config. SetUserIsAlt does this internally.
  if (not isalt and live and cfg:IsActive()) then
    self:RefreshUsers()
    self:RefreshAllMemberLists()
  end
end

--
-- Command: MDUSR uid ench frozen alt main class pprof sprof msrole osrole race level pdata
-- Purpose: Sent to the raid / guild when a user is modified. ENCH and FROZEN are this config's own view of them, MAIN is the
--          uid in this config of whoever they are an alt of, CLASS to LEVEL are what the sender holds to be true of the
--          character, which is where a raid info check's corrections travel, and PDATA is what the policy keeps about them.
--          The event is the whole entry, so a PDATA that is not there is a policy keeping nothing.
--
ehandlers.MDUSR = function(self, live, sender, proto, pol, cmd, cfg, ...)
  local uid, ench, frozen, alt, mainid, class, pprof, sprof, msrole, osrole, race, level, pdata = ...

  -- An admin who is not yet syncing can be sent about a user they never received, just as anybody else can.
  if (not cfg.uids[uid]) then
    return
  end

  cfg:SetUserEnchanter(uid, ench, true)
  cfg:SetUserFrozen(uid, frozen, true)
  cfg:SetUserPData(uid, pdata, true)

  --
  -- ALT is what the sender's copy of this config could see, which is a main it holds a uid for, so false means only that it
  -- saw none. It never means the person has no main. Whose alt somebody is is the mod's and is the same answer in every
  -- config of every mod, and this config not holding their main does not unmake it, so acting on the false would unlink that
  -- character everywhere on the strength of one config that was never going to be able to say.
  --
  -- Saying nothing is therefore read as nothing. The one thing that clears a link is the event that exists to say so,
  -- a CHUSR whose flags do not name A, which an admin sends only by unlinking them by hand.
  --
  if (alt) then
    cfg:SetUserIsAlt(uid, true, mainid, true)
  end

  --
  -- What the game itself can prove about the character is where a sender can be honestly wrong, so that is put to the player.
  -- The alt link above is not one of those. It is what the people running the raid say about the human behind two characters,
  -- and it is written as it stands.
  --
  local name = cfg:UserName(uid)

  if (name) then
    KU:OfferPeople(sender, { { name, class, pprof, sprof, msrole, osrole, race, level } })
  end

  if (live and cfg:IsActive()) then
    self:RefreshUsers()
    self:RefreshAllMemberLists()
  end
end

