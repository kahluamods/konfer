--
-- Command: CINFO mods extras token where
-- Purpose: A group leader or assistant asks the group, or a guild officer the guild, what everybody is running and who they
--          are. MODS names the KahLua mods to report the version of and EXTRAS what else to say. TOKEN is the asker's, and
--          the answer carries it back so they can tell their own check's replies from anything else. WHERE is "GROUP" or
