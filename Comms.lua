--
-- The messages that are not events and are still worth sending once the game stops refusing addon messages, which Kore holds
-- until then: sync, recovery and broadcasts, which carry configs or their loot history. Every event is held as well, a
-- config's checksum and each admin's last event id being counted from them, so konfer:MakeSends asks the sending policy's
-- own ehandlers too. Everything else is live raid traffic that means nothing a minute later, and is dropped.
--
local HELD_MESSAGES = {
  BCAST = true,
  CSYNC = true,
  FSYNC = true,
  GSYNC = true,
  LHBCS = true,
  MSYNC = true,
  RCACK = true,
  RCOVR = true,
  RSYNC = true,
  SYNAK = true,
}

function konfer:HeldMessage(cmd)
  return HELD_MESSAGES[cmd] or false
end

--
-- Whether a message is one of ours to act on at all, from the preamble alone and before anything is looked up. The whole mod
-- hears one prefix, so everything every policy sends arrives here. WHO is a policy name not a player name.
--
-- Two things are refused. A policy no addon on this client registered, which is the sender running something we do not
-- rather than anything being wrong. And one the user has switched off, which is shelved entirely and is brought up to date
-- by syncing when it is switched back on, so what arrives for it while it is off must write nothing.
--
function konfer:AcceptMessage(who)
  if (who == self.CMD_MOD) then
    return true
  end

  if (not self.policies[who] or self:IsPolicyDisabled(who)) then
    return false
  end

  return true
end

--
-- The mod's own messages, the ones named CMD_MOD. Only the mod's own are, so a command that is not one of them means the
-- sender is newer than us.
--
local function mod_commdispatch(self, sender, proto, cmd, cfg, ...)
  if (not mhandlers[cmd]) then
    KC.OldProtoDialog(self)
    return
  end

  mhandlers[cmd](self, sender, proto, nil, cmd, cfg, ...)
end

--
-- A policy's messages: POL is the policy whose name they carry and the table they dispatch through. The handlers themselves
-- are the mod's code whichever policy's copy of the table holds them, and they run on the mod as the rest of it does. A
-- handler that wants the policy asks the config for it.
--
-- An ihandler's arguments are the message's own and start here. An **event** carries six more in front of them, written by
-- lowlevel_add_event in Utility.lua and taken off below, and this is the only place either end of that is described.
--
--   1 scrc     the config's checksum after this event, which the receiver ends up holding if it applies it
--   2 ocrc     the checksum before it, which must be the one the receiver holds now or the two have diverged
--   3 eid      this event's id, the UTC minute it was made in and a counter
--   4 oldeid   the sender's previous event id, which must be the last we had from them or we have missed one
--   5 userevt  whether a receiver who is not an admin of the config acts on it. AddEvent sends true, AdminEvent false
--   6 estr     the event's own arguments, serialised and encoded, unpacked by event_args above
--
-- An ehandler therefore never sees any of them. It is given the same first six values every handler is, and then the
-- arguments its sender passed to AddEvent.
--
local function policy_commdispatch(pol, sender, proto, cmd, cfgid, ...)
  local self = konfer

  --
  -- A message names its config by id, that being the only name for one that can travel. Everything past here is handed the
  -- config itself, so a handler asks it questions rather than looking it up again in every line.
  --
  -- About a config of this policy's that we do not hold, so not ours to act on.
  --
  local cfg = cfgid and self:PolicyConfig(pol, cfgid)

  if (cfgid and not cfg) then
    self.debug(4, "%q from %q dropped: config %q is not held", cmd, sender, tostring(cfgid))
    return
  end

  --
  -- Every handler past here is given a config, and the two that are not are the two that deliberately name none. That is
  -- what lets a handler read cfg without asking first: an event is refused below for naming no config, and an ihandler is
  -- refused here, so the only way to see nil is to be one of the pair that never has one.
  --
  if (pol.ihandlers[cmd]) then
    if (not cfg and not CONFIGLESS[cmd]) then
      self.debug(4, "%q from %q names no config", cmd, sender)
      return
    end

    if (requirements_met(self, sender, cmd, cfg)) then
      pol.ihandlers[cmd](self, sender, proto, pol, cmd, cfg, ...)
    end
    return
  end

  --
  -- Anything else must be one of this policy's events. A command it does not know at all means the sender is newer than us,
  -- and an event is always about a config.
  --
  if (not pol.ehandlers[cmd]) then
    KC.OldProtoDialog(self)
    return
  end

  if (not cfg) then
    self.debug(4, "%q from %q names no config", cmd, sender)
    return
  end

  local adm = cfg:MyStatus()
  local scrc, ocrc, eid, oldeid, userevt, estr = ...

  if ((not adm) and (not userevt)) then
    -- We're not an admin and this is an admin-only event - return.
    return
  end

  --
  -- Only an admin of the config can change it, so an event from anybody else is ignored, by admins and non-admins alike.
  -- Whether an event is for everybody is the sender's say, and who the sender is is not.
  --
  local senduid = cfg:FindUser(sender)
  if (not senduid) then
    return
  end

  --
  -- When we check to see if we are an admin, the call checks to see if the sender is an alt, and that the alt's main is the
  -- owner or and admin. It always returns the real ID of the user's main if this user is an alt. We capture that user ID to
  -- use for checking the sender's credentials by ID, as that is the actual user we care about.
  --
  local ia, cksenduid = cfg:IsAdmin(senduid)
  if (not cksenduid) then
    cksenduid = senduid
  end

  if (not ia) then
    return
  end

  --
  -- Decoded before anything is folded in, so an event that cannot be read changes nothing. Folding first would move the
  -- running checksum and record the sender's latest event for one that was then dropped, and the two of us would be out of
  -- step for good: the eventids would agree and the checksums would not, which is the one thing the test below cannot
  -- recover from. MSYNC does it in this order for the same reason.
  --
  local args = event_args(estr)
  if (not args) then
    self.debug(1, "decoding issue with %q from %q", cmd, sender)
    return
  end

  if (adm) then
    --
    -- Here we need to see if we are up to date with the sender, by checking to see if our last eventid matches their oldeid
    -- they just sent us. If it does, we process the event. If not, we ignore it because it means we are out of sync.
    --

    --
    -- If we are an admin and we havent started a sync relationship with anyone yet, we can still process the event below (it
    -- does no harm and will keep their config as up to date as possible). There is no real benefit to doing this except that
    -- we can, and an unsynced admin will still have a rough idea of what's what with the configuration. However, if we are
    -- syncing, we need to check to see if the last event we received from this user was the same as we have recorded for
    -- them, and if so, process the event as per normal. If not, we simply return as it means we are out of sync with
    -- respects to the sender, and we need to do a sync.
    --
    if (cfg.syncing) then
      if (cfg.admins[cksenduid].lastevent ~= oldeid) then
        return
      end

      local oldsum = cfg.cksum
      if (oldsum ~= tonumber(ocrc, 16)) then
        return
      end

      local newsum = bxor(oldsum, tonumber(scrc, 16))

      --
      -- If we get down here it means we are a syncer, the sender is a syncer, and we are up to date with respects to each
      -- other. We need to update the config checksum with this new event, and update the last event received from this sender.
      --
      cfg.cksum = newsum
      cfg.admins[cksenduid].lastevent = eid

      if (konfer.qf and konfer.qf.synctopbar) then
        konfer.qf.synctopbar:SetCurrentCRC()
      end

      cfg:SyncReplierEvent(cksenduid, eid, newsum)
    end
  end

  --
  -- Every event handled here arrived on its own, whoever received it, so the handler is told it is live and redraws what it
  -- changed. An event replayed in a sync batch (MSYNC) is not, the batch redrawing once when it is done.
  --
  pol.ehandlers[cmd](self, true, sender, proto, pol, cmd, cfg, unpack(args, 2, args.n))
end

--
-- Everything this mod hears, all of it arriving under the one prefix, and the only place the preamble every message carries
-- is taken apart. Kore has checked the message arrived as it was sent and handed back the values as they were passed; which
-- of them mean what is entirely this mod's, and it is this function that knows.
--
-- RES says whether the payload deserialised at all. Then the four the sends put there: the sender's protocol, the endpoint
-- that sent it, the command, and the config it is about.
--
local function commdispatch(self, sender, dist, res, proto, who, cmd, cfg, ...)
  if (not res) then
    self.debug(9, "undecodable message from %q", sender)
    return
  end

  --
  -- Believed only once Kore's checksum has said the message is what was sent, so a mangled one cannot claim to come from a
  -- newer peer. A protocol above ours means arguments we have no way to read, so nothing is looked at beyond this.
  --
  if (type(proto) ~= "number" or proto > self.protocol) then
    KC.OldProtoDialog(self)
    return
  end

  if (not self:AcceptMessage(who)) then
    return
  end

  -- Sent as false rather than left out, so the slot is there to take off whatever came.
  if (not cfg) then
    cfg = nil
  end

  if (who == self.CMD_MOD) then
    return mod_commdispatch(self, sender, proto, cmd, cfg, ...)
  end

  return policy_commdispatch(self.policies[who], sender, proto, cmd, cfg, ...)
end

function konfer:OnCommReceived(prefix, msg, dist, snd)
  return self:KonferCommReceived(prefix, msg, dist, snd, commdispatch)
end

--
-- Command: DEBUG level message ... Purpose: Displays a debug message from the given sender
--
mhandlers.DEBUG = function(self, sender, proto, pol, cmd, cfg, ...)
  local lev, msg = ...
  -- The message is shown as it came, never used as a format, so a stray % from another client cannot raise an error here.
