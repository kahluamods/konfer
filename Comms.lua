  -- lists while their checksums agree, this being a change to the lists that is no event of its own. FixupLists guards its
  -- own redraw on the config being the active one, so nothing is drawn here that was not drawn before.
  --
  cfg:FixupLists()

  if (live and cfg:IsActive()) then
    self:RefreshListsUI(false)
  end
end

