-- Purpose: Sent when the master looter stops looting a corpse or chest. Close the main window when we receive this if we
--          opened it during OLOOT processing.
--
ihandlers.CLOOT = function(self, sender, proto, pol, cmd, cfg, ...)
  self:CloseLoot()
  if (we_opened) then
    we_opened = nil
    self.mainwin:Hide()
  end
end

