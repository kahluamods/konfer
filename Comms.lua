--
-- Command: CHITM itemid ign cfilter role list rank nextuser awardlist del autoassign ignqual pdata
-- Purpose: This is a syncer-only event and deals with modifying an item in the item database. The item must already exist.
--          IGN is true if the item is to be ignored, which puts the rest out of use and leaves them kept. If there is a class
--          specific filter for the item it is passed in CFILTER, otherwise that is the empty string. ROLE is the role or 0
--          for none. LIST is the list ID of a list to roll on, or the empty string for none. RANK is the guild rank filter,
--          0 for none. If the next drop is meant to be assigned to a given user, the user's ID is passed in NEXTUSER, else
--          it is the empty string. If it is not empty, DEL is true if the item is to be deleted after the next assignment,
--          and AWARDLIST is the list the award is applied on, or false for none. AUTOASSIGN says who the item goes to
--          without a bid or roll, one of the AUTOASSIGN_ constants. IGNQUAL is true if the item is offered whatever its quality.
--          PDATA is what the config's policy keeps on the item for itself, false for nothing, taken as it stands and never read.
--
ehandlers.CHITM = function(self, live, sender, proto, pol, cmd, cfg, ...)
  local itemid, ign, cfilt, role, lst, rank, nextuser, slist, del, autoassign, ignqual, pdata = ...

  local ilist = cfg.items
  if (not ilist[itemid]) then
    return
  end

  --
  -- An ignored item keeps the rest of its instructions, which put out of use by the ignore are still the item's.
  --
  local ii = {ilink = ilist[itemid].ilink }
  if (ign) then
    ii.ignore = true
  end
  if (cfilt and cfilt ~= "") then
    ii.cfilter = cfilt
  end
  if (role and role ~= "") then
    ii.role = tonumber(role)
  end
  if (lst and lst ~= "") then
    ii.list = lst
  end
  if (rank and rank ~= "") then
    ii.rank = tonumber(rank)
  end
  if (nextuser and nextuser ~= "") then
    ii.user = nextuser

    if (slist and slist ~= "" and slist ~= "0") then
      ii.awardlist = slist
    end
    if (del) then
      ii.del = true
    end
  end
  local aa = tonumber(autoassign) or self.AUTOASSIGN_NOBODY
  if (aa ~= self.AUTOASSIGN_NOBODY) then
    ii.autoassign = aa
  end
  if (ignqual and ignqual ~= "") then
    ii.ignorequal = true
  end
  if (pdata ~= nil and pdata ~= false) then
    ii.pdata = pdata
  end
  ilist[itemid] = ii

  if (live and cfg:IsActive()) then
    self:RefreshItemList()
  end
end

--
-- Command: CHSET opts vals
-- Purpose: Syncer-only event sent when any of a config's settings is changed. It carries both of the strings the config
--          keeps them in rather than the one setting that moved: they are small, and an admin who missed an earlier one
--          still ends up holding exactly what the sender holds. konfer:MakeConfig is what reads them by name.
--
ehandlers.CHSET = function(self, live, sender, proto, pol, cmd, cfg, opts, vals)
  --
  -- Both strings or neither. A string of the wrong length is a sender whose build declares a different number of settings,
  -- which is a protocol mismatch wearing the right shape, and taking it would shift every setting after the difference.
  --
  if (type(opts) ~= "string" or type(vals) ~= "string" or strlen(opts) ~= #self.copts) then
    return
  end

  cfg.opts = opts
  cfg.vals = vals

  -- The raid's disenchanters are the active config's, and any of this may have moved them.
  if (cfg:IsActive()) then
    self:UpdateDenchers()
  end

  if (live and cfg:IsActive()) then
    self:RefreshConfigUI(false)
  end
end

--
-- Command: PSSET handle block
-- Purpose: Syncer-only event sent when any of a policy's own settings is changed. HANDLE names the policy whose block it
--          belongs in and BLOCK is the whole of that block, not the one setting that moved, so that an admin who missed an
--          earlier one still ends up holding exactly what the sender holds.
--
--          The platform's twin of this is CHSET, and the two are apart so that neither side has to know what is in the
--          other's table. A policy may call a setting whatever it likes; the name is only ever looked up in its own defaults.
--
ehandlers.PSSET = function(self, live, sender, proto, pol, cmd, cfg, handle, block)
  --
  -- A policy this client does not run is somebody in the raid running a system we do not have, and the config it is about
  -- is one we cannot be holding either. Everything inside the block is checked against what that policy declares, so a name
  -- it has never heard of or a value of the wrong kind is dropped and the rest is still taken.
  --
  if (type(handle) ~= "string" or not self.policies[handle]) then
    return
  end

  cfg:SetPolicySettings(handle, block)

  if (live and cfg:IsActive()) then
    self:RefreshConfigUI(false)
  end
end

--
-- Command: MKADM userid adminid
-- Purpose: Sent when an admin is added to the list of admins. Can only ever be sent by the config owner.
--
ehandlers.MKADM = function(self, live, sender, proto, pol, cmd, cfg, ...)
  local uid, adminid = ...

  if (not sent_by_owner(cfg, sender)) then
    return
  end

  --
  -- A new admin has sent no events yet, and the first they send says its predecessor was 0, so that is what they are
  -- recorded as having sent. Somebody who is an admin already keeps what we know of their sync.
  --
  if (cfg.admins[uid]) then
    cfg.admins[uid].id = adminid
  else
    cfg.nadmins = cfg.nadmins + 1
    cfg.admins[uid] = { id = adminid, lastevent = 0 }
  end

  --
  -- Being made an admin ourselves changes which pages we may see. Otherwise any window's Admin tab may have this config
  -- selected, whichever policy is active, and keeps what it has selected.
  --
  local _, mymain = cfg:IsAlt(cfg:MyUid())
  if (uid == cfg:MyUid() or uid == mymain) then
    self:FullRefresh(false)
  else
    self:RefreshConfigAdminUI(false)
  end
end

--
-- Command: RMADM userid
-- Purpose: Sent when an admin is removed from the list of admins. Can only ever be sent by the config owner.
--
ehandlers.RMADM = function(self, live, sender, proto, pol, cmd, cfg, ...)
  local uid = ...

  -- The owner is not an admin to be removed, and nobody but the owner removes anybody.
  if (uid == cfg.owner or not sent_by_owner(cfg, sender)) then
    return
  end

  --
  -- If I was just removed as an admin, get rid of any sync data I may have had for other users. Also need to check to see if
  -- I am an alt and my main was just removed as an admin.
  --
  local _, mymain = cfg:IsAlt(cfg:MyUid())
  local me = (uid == cfg:MyUid() or uid == mymain)
  if (me) then
    cfg.syncing = false
    cfg.lastevent = 0
    cfg.nitems = 0
    cfg.items = {}
    cfg.cksum = 0
    cfg.history = {}
    for k,v in pairs(cfg.admins) do
      v.sync = nil
      v.lastevent = nil
      v.active = nil
    end
  end

  cfg:DeleteAdmin(uid, true)

  -- No longer being an admin changes which pages we may see in whichever window shows this config.
  if (me or cfg:IsActive()) then
    self:FullRefresh()
  end
end

--
-- Command: RSYNC
-- Purpose: This is a syncer-only event and is sent either directly to an individual user via whisper, or to the guild or
--          raid if the "request all" sync button was pressed. Only users who are syncers will respond to the event. Responds
--          with a SYNAK message to the sender, no matter how we receieved it (from the receiver's perspective we cant tell
--          and don't care if we got this as a whisper or a guild/raid broadcast, we respond identically). We keep a table of
--          who sent us sync requests about which config and when, and ignore multiple requests for one config if they come
--          within 10 seconds of each other, in case the sender is spamming the sync request button. A request about another
--          config, or the same id in another policy, is a different request.
--
local lastrec = {}
ihandlers.RSYNC = function(self, sender, proto, pol, cmd, cfg, ...)
  local now = K.time()
  local reckey = strfmt("%s:%s:%s", sender, cfg:GetPolicy().handle, cfg.id)
  if (lastrec[reckey]) then
    if ((now - lastrec[reckey]) < 10) then
      return
    end
  end
  lastrec[reckey] = now

  if (not cfg:MyStatus()) then
    return
  end

  --
  -- I'm an admin in this config. Check to see if the sender is an admin too. If I don't know they are an admin, it means I
  -- am out of date with respects to the config owner, and I need to sync with them first. We will issue a warning for this case.
  --
  local theiruid = cfg:FindUser(sender)
  if (theiruid == nil or not cfg:IsAdmin(theiruid)) then
    cfg:GetPolicy():info(
      L["sync request received from %q but I do not recognise them as an admin. Please sync with the config owner (%q)."],
      sender, aclass(cfg:UserNameClass(cfg.owner)))
    return
  end

  --
  -- All good. We think we're a syncer, we think they're a syncer, we will respond. We reply with the highest event number we
  -- have, and our CRC. The person who requested the sync will use this to determine whether or not they need any events from
  -- us. If they do they will send us a GSYNC message requesting all events from a certain number forward.
  --
  cfg:GetPolicy():CSendWhisperAM(cfg.id, sender, "SYNAK", "ALERT", cfg.lastevent, cfg.cksum)
end

--
-- Command: SYNAK lastevent cksum
-- Purpose: This is a syncer-only event and is sent in reply to us requesting sync info from a user or users. We need to
--          verify that the user really is an admin (as we know things) and reject any replies from users we don't know as
--          admins. We then pass this up to the sync code to determine if we need any events from the user who replied.
--          LASTEVENT is the highest event number the sender has in their logs, and CKSUM is their config checksum.
--
ihandlers.SYNAK = function(self, sender, proto, pol, cmd, cfg, ...)
  local lastevt, cksum = ...

  --
  -- A sync reply about a config we are not an admin of, or are not even in, is most likely somebody trying to spoof us, so
  -- it is silently ignored. MyStatus answers false for a config this character has no uid in, so the one test covers both.
  --
  local myuid = cfg:MyUid()

  if (not cfg:MyStatus()) then
    return
  end

  --
  -- I'm an admin in this config. Check to see if the sender is an admin too. If I don't know they are an admin, silently ignore the reply.
  --
  local theiruid = cfg:FindUser(sender)
  local ia, cktheiruid = cfg:IsAdmin(theiruid)
  if (theiruid == nil or not ia) then
    return
  end

  cfg:ProcessSyncAck(myuid, theiruid, cktheiruid, lastevt, cksum)
end

--
-- Command: GSYNC lastevent full lasteid cksum
-- Purpose: This is a syncer-only event and is sent by a user requesting sync information from us. LASTEVENT is the last
--          event they have from us (which can be 0). If FULL is true, it means they are requesting a full sync with us, as
--          they do not have any existing sync relationships. This affects the return config we send them by adding in the
--          list of admins we are synced with and the last event we have received from all the admins we know about. If we
--          were not already marked as syncing with other users, we do so now (syncing = true for the config space) because
--          we have just entered into a sync relationship with the sender. Note that in the case of a full sync we actually
--          reply with a FSYNC event. If FULL is false, then this is a normal sync event, and we use LASTEVENT to determine
--          exactly which events we need to send to the user. All events after LASTEVENT are sent as a single large table.
--          LASTEID is the sender's current highest event ID, which can be 0 if this is a first time full sync for them.
--          CKSUM is provided for possible future use and is the senders current config checksum value.
--
ihandlers.GSYNC = function(self, sender, proto, pol, cmd, cfg, ...)
  local lastevt, full, lasteid, cksum = ...

  local theiruid = cfg:FindUser(sender)
  local ia, cktheiruid = cfg:IsAdmin(theiruid)
  if (theiruid == nil or not ia) then
    return
  end

  if (full) then
    if (cfg:MyStatus() == 2) then
      cfg:GetPolicy():info(L["[%s] sending sync data to user %s."], white(cfg.name),
        aclass(cfg:UserNameClass(theiruid)))

      cfg:SendFullSync(sender, false)
    end
    return
  end

  --
  -- The more usual case, send the person the list of events since the last one they receieved. Note that this may actually
  -- be the first time we are receiving any data from this user, so they may not be marked as "active". However, after this
  -- operation, they will be. So we mark them as active. We can be inactive and still have normal events for them since if
  -- they just got a full sync, they could have picked up from whoever they did it with that they were up to date up to a certain event ID.
  --
  local mlist = {}
  local them = cfg.admins[cktheiruid]

  them.active = true

  if (not them.lastevent) then
    them.lastevent = 0
  end

  if (not them.sync) then
    them.sync = { }
  end

  for k,v in pairs(them.sync) do
    if (v[2] > lastevt) then
      tinsert(mlist, v)
    end
  end

  cfg:GetPolicy():info(L["[%s] sending sync data to user %s."], white(cfg.name),
    aclass(cfg:UserNameClass(theiruid)))

  cfg:GetPolicy():CSendWhisperAM(cfg.id, sender, "MSYNC", "ALERT", cfg:MyUid(), theiruid, mlist)
end

--
-- Command: FSYNC cfgdata
-- Purpose: This is a syncer-only event and is sent in response to a GSYNC message above when a full sync is requested. We
--          need to verify that we did in fact request this, and that the sender is who we expect it to be.
--
ihandlers.FSYNC = function(self, sender, proto, pol, cmd, cfg, ...)
  local cfgd = ...

  if (not cfg:MyStatus()) then
    return
  end

  --
  -- I'm an admin in this config. Check to see if the sender is an admin too. If I don't know they are an admin, silently ignore the reply.
  --
  local theiruid = cfg:FindUser(sender)
  if (theiruid == nil or not cfg:IsAdmin(theiruid)) then
    return
  end

  -- A full sync replaces the whole config, so it is accepted only from somebody it was asked of, and only once.
  if (not fullsyncs_asked[cfg.id] or not fullsyncs_asked[cfg.id][sender]) then
    return
  end

  fullsyncs_asked[cfg.id][sender] = nil

  local ncf, cfgid, people, links = prepare_config_from_bcast(self, cfgd)

  if (not ncf) then
    return
  end

  ncf.syncing = true
  self:AdoptPeople(sender, ncf, people)
  self:KeepLocalConfigState(ncf, cfg.id)

  -- A full sync replaces a config we already hold, so it stays with the policy that holds it.
  local pol = cfg:GetPolicy()

  self:SetConfig(cfg.id, ncf, pol)
  ncf:AdoptListInfo()
  self:AcceptAltLinks(links)

  --
  -- The config is a new table now, and a policy holding the old one would go on showing it and editing it, whether or not
  -- the policy is the active one.
  --
  if (cfg:IsActive()) then
    self:MakeAliases()
    self:FullRefresh(true)
  end
  pol:info(L["[%s] sync with user %s complete."], white(ncf.name), K.DisplayName(sender))

  --
  -- We will want to clear the list of syncers so that we don't attempt to get another full sync from someone else.
  --
  cfg:SyncUpdateReplier()
  ncf:PolicyCall("ConfigSynced", nil, "full")
end

--
-- Command: MSYNC theiruid myuid modlist
-- Purpose: This is a syncer-only event and is sent in response to a GSYNC when they want events after a specific number, and
--          it is not a full sync (which is handled by FSYNC above). THEIRUID is the sender's UID in the config in question,
--          MYUID is my uid in that same config (they calculated it, its a matter of choice that we trust it) and MODLIST is
--          a table with event strings that need to be split and processed.
--
ihandlers.MSYNC = function(self, sender, proto, pol, cmd, cfg, ...)
  local theiruid, myuid, mlist = ...

  local ia, cktheiruid = cfg:IsAdmin(theiruid)
  if (not cfg.uids[theiruid] or not ia) then
    return
  end

  -- The events are the sender's own, so the sender has to be who the batch says it is from.
  local senduid = cfg:FindUser(sender)
  if (not senduid) then
    return
  end

  local _, cksenduid = cfg:IsAdmin(senduid)
  if (cksenduid ~= cktheiruid) then
    return
  end

  if (not cfg.uids[myuid] or not cfg:IsAdmin(myuid)) then
    return
  end

  local pol = cfg:GetPolicy()

  for k,v in pairs(mlist) do
    --
    -- The four fields a queued event is stored as. They arrive from another client, so nothing about their shape is
    -- believed until it has been looked at. A handler that indexed a number or CRCed a table would raise inside the comms
    -- callback. See cfg:AddEvent for where these are built.
    --
    local cmd, eid, cks, cstr

    if (type(v) == "table") then
      cmd, eid, cks, cstr = v[1], v[2], v[3], v[4]
    end

    if (type(cmd) ~= "string" or type(cstr) ~= "string" or type(cks) ~= "number" or type(eid) ~= "number") then
      pol:err(L["undecodable sync command %q from %q (p=%d)"], tostring(cmd), K.DisplayName(sender), proto)
      return
    end

    if (cks ~= H:CRC32(cstr)) then
      pol:err(L["possible hack attempt: mismatched checksum from %s"], white(K.DisplayName(sender)))
      return
    end

    --
    -- A replayed event stream is one config's, so every event in it should be one this policy answers. Anything else is a
    -- sender running a build we do not understand, and the batch stops there, the events before it kept: the same as having
    -- been present for only those. It stops at the same place every time until this client is upgraded.
    --
    if (not pol.ehandlers[cmd]) then
      pol:err(L["unknown sync command %q from %q (p=%d)"], cmd, K.DisplayName(sender), proto)
      return
    end

    -- Decoded before anything is folded in, so an event that cannot be read stops the batch where it stands.
    local args = event_args(cstr)

    if (not args) then
      pol:err(L["undecodable sync command %q from %q (p=%d)"], cmd, K.DisplayName(sender), proto)
      return
    end

    --
    -- Update our config checksum with the new one and process the event.
    --
    local oldsum = cfg.cksum
    local newsum = bxor(oldsum, cks)

    cfg.cksum = newsum
    cfg.admins[cktheiruid].lastevent = eid

    -- Not live: the whole batch is redrawn once, below.
    pol.ehandlers[cmd](self, false, sender, proto, pol, cmd, cfg, unpack(args, 2, args.n))
  end

  if (konfer.qf and konfer.qf.synctopbar) then
    konfer.qf.synctopbar:SetCurrentCRC()
  end

  cfg.admins[cktheiruid].active = true
  if (not cfg.admins[cktheiruid].sync) then
    cfg.admins[cktheiruid].sync = {}
  end

  cfg:SyncUpdateReplier(theiruid, cfg.admins[cktheiruid].lastevent)
  pol:info(L["[%s] sync with user %s complete."], white(cfg.name),
    aclass(cfg:UserNameClass(theiruid)))

  self:FullRefresh(true)
  cfg:PolicyCall("ConfigSynced", nil, "events")
end

--
-- Command: CSYNC table
-- Purpose: This is a syncer-only event and is sent to either the guild or the raid and contains a table of all known guild
--          or raid configurations, along with the list of co-admins we are syncing with and their last known event we
--          receieved from them. This is used by the recipient to remove any events prior to that event, as it means the
--          sender already has those events safely saved in their savedvariables folder. This event is only ever sent once by
--          each user when they first log in (or reload their UI).
--
mhandlers.CSYNC = function(self, sender, proto, pol, cmd, cfg, cfgt)
  for k,v in pairs(cfgt) do
    local cfgid, nadm, astr = strsplit(":", v)
    local pp = self:GetPolicy(cfgid)
    local cfg = self:Config(cfgid)
    nadm = tonumber(nadm)

    -- A switched off policy's configs are shelved, and nothing arriving changes them.
    if (pp and cfg and not self:IsPolicyDisabled(pp.handle)) then
      local cap = cfg.admins
      local myuid = cfg:MyUid()
      local mymainid = cfg:MyMainId()
      local theiruid = cfg:FindUser(sender)

      if (theiruid) then
        if (not cap[theiruid]) then
          local ia, aid = cfg:IsAlt(theiruid)
          if (ia and cap[aid]) then
            theiruid = aid
          else
            theiruid = nil
          end
        end
      end

      if (myuid and theiruid and cap[theiruid].sync) then
        for i = 1, nadm do
          local admid = strsub(astr, 1, 4)
          local lastid = tonumber(strsub(astr, 5, 18))
          astr = strsub(astr, 19)
          if (admid == myuid or admid == mymainid) then
            --
            -- Everything up to LASTID they have, whether or not anything newer is waiting, so only what is newer stays.
            --
            local keep = {}

            for kk,vv in ipairs(cap[theiruid].sync) do
              if (vv[2] > lastid) then
                tinsert(keep, vv)
              end
            end

            cap[theiruid].sync = keep
          end
        end
      end
    end
  end
end

--
-- Command: RCOVR name
-- Purpose: This is a syncer-only event and is sent by a config owner (which is verified by the recipient) when they want to
--          recover their config. We essentially respond with the same data as FSYNC above with a little extra for the full
--          config checksum, history and last known event ID stuff. The sender then processes that reply to rebuild their
--          configuration after some kind of disaster. NAME is the name of the config we want to recover. We cannot use the
--          config ID as the owner may have had to create a whole new config, and the reply will include the config ID, which
--          will update the sender's config ID when they receive the data.
--
--
-- This and RCACK name no config in the envelope, alone among the policy's messages, the owner recovering one being able to
-- hold it under an id the admin answering does not or under none at all. So the config is found by name, in the policy the
-- envelope named, which is the one thing about a recovery that does not have to be said twice.
--
ihandlers.RCOVR = function(self, sender, proto, pol, cmd, cfg, cfgname)
  --
  -- The one command that arrives with no config in the envelope, so the config here is found by name inside the policy the
  -- command named. CFG above is nil for exactly that reason and is not what this works on.
  --
  local found = self:FindConfig(pol, cfgname)
  local theirs = found and self:Config(found)

  if (not theirs or not sent_by_owner(theirs, sender)) then
    return
  end

  --
  -- If I am not an admin (or think I'm not) then ignore.
  --
  if (theirs:MyStatus() ~= 1) then
    return
  end

  theirs:SendFullSync(sender, true)
end

