  end

  self:SelectLootListByID(listid)
end

--
-- Unpack a broadcast or full sync config.
--
local function istable(v)
  return type(v) == "table"
end

local function prepare_config_from_bcast(self, cfd)
  local ncf = {}
  local cfgid = nil
  local cfgname, owner, crc, policy, channel
  local people = {}
  local links = {}

  --
  -- Refused rather than decoded. There is one shape and this says which one it is, so anything else is a mod we cannot talk
  -- to rather than a message to interpret differently.
  --
  if (not istable(cfd) or cfd.v ~= konfer.BCAST_VERSION) then
    debug(2, "BCAST returning: broadcast version %s", tostring(istable(cfd) and cfd.v))
    return nil, nil
  end

  --
  -- The other half of that one shape. Everything below either walks one of these or unpacks it, and neither survives being
  -- handed a string or a number where a table was promised, so the whole shape is settled here in one place. A payload that
  -- is not what it says it is leaves as a refusal like any other, rather than as an error raised inside the comms callback
  -- with a broadcast half applied behind it. The last two are a full sync's extras and are checked only when they are there.
  --
  if (not istable(cfd.c) or not istable(cfd.u) or not istable(cfd.a) or not istable(cfd.l)) then
    debug(2, "BCAST returning: malformed payload")
    return nil, nil
  end

  if ((cfd.s and not istable(cfd.s)) or (cfd.i and not istable(cfd.i))) then
    debug(2, "BCAST returning: malformed sync data")
    return nil, nil
  end

  local opts, vals

  cfgid, cfgname, owner, crc, policy, channel, opts, vals = unpack(cfd.c, 1, 8)

  --
  -- Which policy's configs this goes into is the sender's to say, there being nothing to look it up in for a config we do
  -- not hold. A policy we do not have is a config we cannot keep, and a config naming none at all is not one we can file
  -- anywhere. Both are refused here, at the doorway, so nothing past this has a policy to guess at.
  --
  if (type(policy) ~= "string" or policy == "") then
    debug(1, "BCAST returning: config %q names no policy", tostring(cfgname))
    return nil, nil
  end

  if (not self.policies[policy]) then
    debug(2, "BCAST returning: unknown or disabled policy %s", tostring(policy))
    return nil, nil
  end

  ncf.name = cfgname
  ncf.owner = owner
  ncf.policy = policy
  ncf.channel = channel
  ncf.opts = (type(opts) == "string") and opts or nil
  ncf.vals = (type(vals) == "string") and vals or nil
  ncf.cksum = tonumber(crc, 16) or 0
  ncf.lastevent = 0

  if (ncf.cksum == 0) then
    debug(2, "BCAST returning: invalid checksum")
    return nil, nil
  end

  --
  -- The policy's own settings, checked here against what that policy declares rather than taken as the sender wrote them.
  -- A block for a policy this client does not run is dropped whole, there being nothing to check it against and no way to
  -- run the config it belongs to either. Any declared setting the block leaves out is filled in with its default the first
  -- time the block is asked for, in cfg:PolicySettings.
  --
  ncf.psettings = {}

  if (istable(cfd.p)) then
    for handle, block in pairs(cfd.p) do
      if (self.policies[handle]) then
        ncf.psettings[handle] = self:CleanPolicySettings(handle, block)
      end
    end
  end

  -- The policy's own data on the config (cfg:PolicyData), checked the same way.
  ncf.pdata = {}

  if (istable(cfd.o)) then
    for handle, block in pairs(cfd.o) do
      if (self.policies[handle]) then
        ncf.pdata[handle] = self:CleanPolicyData(handle, block)
      end
    end
  end

  ncf.nusers = 0
  ncf.uids = {}

  for k,v in pairs(cfd.u) do
    --
    -- A row that is not a row refuses the whole message rather than being passed over. The lists below are built of uids and
    -- name the people in this table, so a config missing one of them is a config whose lists point at nobody.
    --
    if (not istable(v)) then
      debug(2, "BCAST returning: malformed user %s", tostring(k))
      return nil, nil
    end

    --
    -- Unpacked to an explicit length, a row with nothing known for one of its fields having a hole in it. PDATA is what the
    -- config's policy keeps about them, taken as it stands for that policy to read.
    --
    local uname, ench, frozen, mainname, facts, pdata = unpack(v, 1, 6)

    --
    -- The character is named as the sender knows them, and turned into this client's KUID only once the config is accepted
    -- (konfer:AdoptPeople). A name that names nobody could never become one, and is refused here with the row.
    --
    if (type(uname) ~= "string" or not K.CanonicalName(uname)) then
      debug(2, "BCAST returning: bad user name %s", tostring(uname))
      return nil, nil
    end

    ncf.uids[k] = { uname, ench or nil, frozen or nil, pdata }
    ncf.nusers = ncf.nusers + 1

    tinsert(people, istable(facts) and facts or { uname })

    --
    -- Both halves of a link are character names, so there is nothing to resolve and nothing that can fail to resolve. An
    -- empty main is the sender saying nothing about this person rather than saying they have none, which is why a link is
    -- only ever written from here and never cleared.
    --
    if (mainname and mainname ~= "") then
      tinsert(links, { uname, mainname })
    end
  end

  --
  -- The mains named above that the sender's config does not itself hold, as people and nothing else. They are offered like
  -- everybody else and are given no uid, because being somebody's main is not being a member of this config.
  --
  if (istable(cfd.m)) then
    for mname, row in pairs(cfd.m) do
      tinsert(people, istable(row) and row or { mname })
    end
  end

  ncf.nadmins = 0
  ncf.admins = {}
  for k,v in pairs(cfd.a) do
    ncf.admins[k] = { id = v }
    ncf.nadmins = ncf.nadmins + 1
  end

  ncf.nlists = 0
  ncf.lists = {}
  for k,v in pairs(cfd.l) do
    if (not istable(v)) then
      debug(2, "BCAST returning: malformed list %s", tostring(k))
      return nil, nil
    end

    local lname, sorder, drank, sc, sr, el, alt, adis, ulist, pdata, popts = unpack(v, 1, 11)

    --
    -- PDATA is the sending policy's own word on this list and is carried no further than the config. cfg:AdoptListInfo
    -- hands it over once the config is in place and clears it, there being no event for a config arriving whole.
    --
    ncf.lists[k] = { name = lname, sortorder = sorder, def_rank = drank, strictcfilter = sc, strictrfilter = sr,
                     extralist = el, tethered = alt, altdisp = adis, users = self:SplitRaidList(ulist), pdata = pdata,
                     poptions = {}
                   }

    -- The policies' own options on the list, each checked against what that policy declares, as the p field is above.
    if (istable(popts)) then
      for handle, block in pairs(popts) do
        if (self.policies[handle]) then
          ncf.lists[k].poptions[handle] = self:CleanListOptions(handle, block)
        end
      end
    end
    ncf.nlists = ncf.nlists + 1
  end

  --
  -- The sync positions are about the admins the same message named, and only those. A position for somebody who is not in
  -- that list is a message that disagrees with itself, and the admin it is about is the one thing here we cannot invent.
  --
  if (cfd.s) then
    for k,v in pairs(cfd.s) do
      if (ncf.admins[k]) then
        ncf.admins[k].lastevent = v
      end
    end
  end

  if (cfd.i) then
    ncf.nitems = cfd.i[1]
    ncf.items = {}
    K.CopyTable(cfd.i[2], ncf.items)
  end

  if (cfd.d and cfd.e and ncf.admins[cfd.d]) then
    ncf.syncing = true
    ncf.admins[cfd.d].lastevent = cfd.e
    ncf.admins[cfd.d].active = true
  end

  return ncf, cfgid, people, links
end

--
-- A config's loot history is each client's own and travels with no config, coming row by row as it is written (LHADD) or
-- whole when the master looter broadcasts it (LHBCS). One arriving to replace a config we hold keeps the history we had
-- for it, and when the master looter last broadcast it, and one we never held starts with none. HELDID names the config
-- held now, which is not always the id NCF arrived under.
--
-- Its settings are not ours and are not kept. The owner of a config decides what it does, so the settings come with it and
-- replace whatever this client had, which is the whole reason they are two small strings. A config that arrived without
-- them, from a client older than that, is given the defaults rather than left with none.
--
-- A plain BCAST does not come through here. It keeps the history the same way, by letting K.CopyTable merge the arriving
-- config over the one held rather than clearing it first, which is what handle_cfgdata says it is doing.
--
function konfer:KeepLocalConfigState(ncf, heldid)
  local held = heldid and self:Config(heldid)

  ncf.history = (held and held.history) or {}
  ncf.histsent = held and held.histsent

  self:MakeConfig(heldid, ncf)
end

--
-- Command: BCAST configdata
-- Purpose: Broadcasts the current config.
--
mhandlers.BCAST = function(self, sender, proto, pol, cmd, cfg, cfdata)
  -- Somebody the player has stopped listening to is not unpacked, let alone asked about.
  if (KU:SenderBlocked(sender)) then
    debug(2, "BCAST returning: %s is blocked", tostring(sender))
    return
  end

  local ncf, cfgid, people, links = prepare_config_from_bcast(self, cfdata)

  if (not cfgid) then
    debug(2, "invalid config in BCAST")
    return
  end

  -- A policy the user has switched off is ignored everywhere, and that includes being handed its configs.
  if (self:IsPolicyDisabled(ncf.policy)) then
    debug(2, "BCAST returning: policy %s is switched off", ncf.policy)
    return
  end

  --
  -- The owner's copy is the config, so the owner ignores every broadcast of it. A broadcast is the mod's own message and
  -- names no config in the envelope, so the config is the one in the payload.
  --
  local tcf = self:Config(cfgid)

  if (tcf and tcf:MyStatus() == 2) then
    debug(2, "config owner ignoring BCAST")
    return
  end

  --
  -- One rule, whoever they are and wherever the config came from: an officer of our guild, or whoever is running the group
  -- we are in. Anyone else pushing a config at us is ignored.
  --
  if (not self:IsElevated(sender)) then
    debug(2, "BCAST returning: %s may not broadcast", tostring(sender))
    return
  end

  --
  -- If this is an existing config, and we are an admin, we most probably want to ignore this. However, if we have not yet
  -- started a sync relationship with anyone (even if we know we are a syncer) we accept this.
  --
  if (tcf) then
    local amadmin = tcf:MyStatus()
    local senduid = tcf:FindUser(sender)

    -- Asked only for a sender this config knows, IsAdmin answering about this player when it is given no uid.
    local sendowner = senduid and tcf:IsAdmin(senduid)

    if (sendowner == 2) then
      --
      -- First things first, there are certain key parameters that are not synced, but rather broadcast (the stuff in the
      -- config admin area). The broadcast will have included all of that info so we set it here.
      --
      tcf.name = ncf.name
      tcf.owner = ncf.owner
      tcf.admins = tcf.admins or {}
      tcf.nadmins = 0

      --
      -- An owner broadcast is authoritative with respects to co-admins. So in case we got bogus data previously or if we
      -- have had any form of corruption, we either remove excess admins from our list or add any that are missing (but only their ID).
      --
      for k,v in pairs(ncf.admins) do
        if (not tcf.admins[k]) then
          tcf.admins[k] = v
        end
      end

      for k,v in pairs(tcf.admins) do
        if (not ncf.admins[k]) then
          tcf.admins[k] = nil
        else
          tcf.nadmins = tcf.nadmins + 1
        end
      end

      --
      -- We may no longer be a coadmin.
      --
      tcf:UpdateUserSecurity()
      amadmin = tcf:MyStatus()

      --
      -- However, if we are an admin now, but we are not yet syncing, then it means we are a newly appointed admin and we
      -- should request a full sync from the config owner. The user used to have to do this manually.
      --
      if (amadmin and not tcf.syncing) then
        debug(2, "BCAST new admin return requesting full sync")
        tcf:RequestFullSync(sender)
      end
    end

    if (amadmin and tcf.syncing) then
      debug(2, "BCAST returning: syncing admin")
      return
    end
  end

  local function handle_cfgdata(this, args)
    local newcfgdata = args[1]
    local newcfgid = args[2]

    this:AdoptPeople(sender, newcfgdata, args[3])

    --
    -- What the config's policy wants to know of a copy this client already holds before the broadcast replaces it, to tell
    -- the player afterwards what changed for them (BroadcastArriving and BroadcastArrived in Policy.lua).
    --
    local held = this:Config(newcfgid)
    local hpol = held and held:GetPolicy()
    local before = nil

    if (hpol and hpol.BroadcastArriving) then
      local _, rv = this:PolicyHook(hpol, "BroadcastArriving", nil, hpol.BroadcastArriving, hpol, newcfgid)

      before = rv
    end

    --
    -- The policy travels with the config, and has to: this config is being stored for the first time, so there is nothing to
    -- look it up in and no way to work out whose it is from the id alone.
    --
    if (not this:Config(newcfgid)) then
      --
      -- An id we do not hold, bearing a name we hold under another id, is one config, ours being a copy that was made or
      -- recovered separately and never carried the owner's id. Accepting the broadcast is replacing ours, which is what the
      -- dialog asked about and was answered yes, so ours keeps its settings and its history and then goes, and the policy's
      -- default follows it across. The owner's id is the one that survives, because every event either of us sends names it.
      --
      -- This is what recovery does with the same collision, in konfer:RecoverConfig, and for the same reason. Names are
      -- unique within a policy, so refusing here would refuse the config after the user had already taken it.
      --
      local newpol = this.policies[newcfgdata.policy]
      local heldid = newpol and this:FindConfig(newpol, newcfgdata.name)

      if (heldid) then
        local pdb = this:PolicyDB(newpol)

        this:KeepLocalConfigState(newcfgdata, heldid)
        this:SetConfig(heldid, nil)

        if (pdb and pdb.defconfig == heldid) then
          pdb.defconfig = newcfgid
        end
      end

      if (this:CreateNewConfig(newcfgdata.name, false, true, newcfgid, newcfgdata.policy)) then
        return
      end
    end
    this:RefreshCSData()
    local nc = this:Config(newcfgid)
    local oldadm = nc:MyStatus()
    nc.uids = nil
    nc.nadmins = 0
    nc.admins = nil
    nc.lists = nil
    nc.syncing = false
    nc.cksum = 0
    nc.lastevent = 0
    nc.nitems = 0
    nc.nusers = 0
    nc.items = {}

    -- The policy's own data is the owner's whole, so what the sender no longer holds, reserves cleared or awards undone, goes.
    nc.pdata = nil

    --
    -- A broadcast carries no settings and no history, so copying it in leaves this client's own, or the new config's
    -- defaults. See KeepLocalConfigState.
    --
    K.CopyTable(newcfgdata, nc)

    --
    -- Which user we are in this config is one of the things the copy just replaced, so it is worked out again before anything
    -- below asks. The RefreshCSData above ran against the user list this broadcast has now thrown away, and everything from
    -- here down, SetDefault and the admin check at the foot included, reads MyUid.
    --
    nc:UpdateUserSecurity()

    -- The lists arrived whole, so what the policy says about each of them is handed over now rather than by any event.
    nc:AdoptListInfo()

    --
    -- Accepting the config was accepting the people in it, the one way anybody arrives in the mod from outside, and they were
    -- taken before anything else (konfer:AdoptPeople). Whose alt they are is written now the config is in place.
    --
    this:AcceptAltLinks(args[4])

    if (newcfgid == this.apol.currentid) then
      nc:SetDefault(true, true)
    end
    nc:GetPolicy():info(L["configuration %q updated by %q"], white(nc.name), white(K.DisplayName(sender)))

    if (before ~= nil and hpol == nc:GetPolicy() and hpol.BroadcastArrived) then
      this:PolicyHook(hpol, "BroadcastArrived", nil, hpol.BroadcastArrived, hpol, newcfgid, before)
    end

    this:FullRefresh(true)
    local newadm = nc:MyStatus()
    if (not oldadm and newadm) then
      nc:RequestFullSync(sender)
    end
  end

  --
  -- A config we have never seen is asked about rather than installed. Whoever sent it has already had to be an officer or
  -- the leader of our group, so this is not a security check; it is that being handed an entire config unannounced should be
  -- something you agree to. An update to a config we already hold goes through without asking.
  --
  if (not tcf) then
    local newpol = self.policies[ncf.policy]
    local msg = strfmt(L["PUGCONFIG"], white(sender), newpol.name)
    K.ConfirmationDialog(self, { text = L["Accept configuration"], owner = newpol }, msg, { L["Configuration: %s"], ncf.name },
      handle_cfgdata, { ncf, cfgid, people, links }, nil, 220, nil)
    return
  end

  handle_cfgdata(self, { ncf, cfgid, people, links })
end

