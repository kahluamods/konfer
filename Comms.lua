-- Command: CHLST listid sort rank stricta strictr list tethered altdisp options
-- Purpose: Syncer-only event sent when a list's paramaters are modified. SORT is the sort order, RANK is the initial guild
--          rank filter, STRICTA is true if strict class armor filtering is in place, STRICTR is true if strict role
--          filtering is in place, LIST is the extra list an award also applies to. OPTIONS is the whole of the policy's own
--          block of options on the list (cfg:ListOptions), checked against what the policy declares on arrival.
--
ehandlers.CHLST = function(self, live, sender, proto, pol, cmd, cfg, ...)
