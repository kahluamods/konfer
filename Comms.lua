--
mhandlers.CINFO = function(self, sender, proto, pol, cmd, cfg, ...)
  local mods, extras, token, where = ...

  self:AnswerCharacterInfo(sender, mods, extras, token, where)
end

--
-- Command: CIACK reply token
-- Purpose: The answer to a CINFO, sent to the whole group or guild it was asked of. REPLY is what a character's own client
--          says about them, which is the one answer nobody has to be asked about, so the asker takes the facts in it as
--          they stand and tells every config it administers that holds them (see konfer:AckCFacts). Everybody else who
--          hears it takes only the versions in it.
--
--          That write is why TOKEN is checked first. An answer naming a check we neither ran nor answered, or one too long
--          ago to still be listening for, is dropped before any of it is looked at. See konfer:AwaitingCInfo.
--
mhandlers.CIACK = function(self, sender, proto, pol, cmd, cfg, ...)
  local reply, token = ...
  local ours = self:AwaitingCInfo(token)

  if (not ours and not self:HeardCInfo(token)) then
    debug(4, "CIACK from %q for a check we neither ran nor answered", sender)
    return
  end

  self:AckCInfo(sender, reply, ours)

  if (ours) then
    self:AckCFacts(sender, reply)
  end
end

