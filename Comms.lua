--
-- Command: OLOOT uguid realguid lootidtable
-- Purpose: Sent when the master looter loots a corpse or chest. This is sent each time they do so, whether its for the same
--          mob/chest or not. So, if the ML clicks away from a mob or closes loot due to combat or whatever, a loot close
--          event will be sent, and when they reloot the mob/chest, this event will be sent again. It is always a table with
--          the full list of unresolved loot. Each element in the table is the itemlink and quantity for the item in
--          question, and what the master looter's policy says it costs (konfer:LootPrice), "75+" or "125", or false, so
--          that a raider's loot list shows the prices the master looter's does.
--
--          UGUID identifies the source and REALGUID says whether it identifies it well enough to be worth remembering. A
--          real mob has a GUID of its own and REALGUID is true. A chest has no GUID, so KLD makes one out of what is inside
--          it, and an item added by hand has no source at all; both of those are REALGUID false and neither is ever taken
--          for a source we have already seen.
--          What the source is called does not travel. Nothing here has ever shown it, and it is two values on every loot of
--          every boss for a mod that is about who gets the item rather than what dropped it.
--
local we_opened = nil

ihandlers.OLOOT = function(self, sender, proto, pol, cmd, cfg, ...)
  local uguid, realguid, loottbl = ...

  self:ResetBossLoot()
  self.raid.bossloot = {}

  for k,v in ipairs(loottbl) do
    local ilink, quant, price = unpack(v)
    local itemid = match(ilink, "item:(%d+)")
    local ti = { itemid = itemid, ilink = ilink, slot = 0, quant = quant, price = type(price) == "string" and price or nil }
    tinsert(self.raid.bossloot, ti)
  end

  self:RefreshBossLoot(nil)

  --
  -- A source is opened for us once a raid, and a source that cannot be told from another one of its kind every time. Only a
  -- real GUID is an identity, so only a real GUID is filed and only a real GUID is looked up: two chests holding the same
  -- things, or two items added by hand, are not the same source and must not silence each other.
  --
  if (realguid) then
    self.raid.autolooted = self.raid.autolooted or {}

    if (self.raid.autolooted[uguid]) then
      return
    end

    self.raid.autolooted[uguid] = true
  end

  -- An admin opens as the config says, anybody else as they said for themselves on the Options page.
  local autoopen = cfg.settings.auto_bid

  if (not cfg:MyStatus()) then
    autoopen = not self.chardb.noautoopen
  end

  if (self:IsSuspended() or not autoopen) then
    return
  end

  --
  -- Loot runs against whichever policy is active, so its window is the one that opens on the master looter's say-so.
  --
  local mainwin = self.mainwin

  if (not mainwin:IsShown()) then
    mainwin:Show()
    mainwin:SetPage(self.LOOT_PAGE, self.LOOT_ASSIGN_TAB)
    we_opened = true
  end
end

