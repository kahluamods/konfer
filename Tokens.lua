-- TOKENS
--
-- An item that is traded in for a piece of gear, a tier token above all, cannot be equipped itself, so the game says
-- nothing about the slot it stands for. This is that slot: every such token of every game, from Zul'Gurub to the current
-- season, and the equip location of the gear it turns into. A token that turns into gear in more than one slot, one class's
-- shoulders and another's boots, is not here and stands for no slot at all. That is a fact about the game's items and not an
-- opinion of any policy's, so it is the platform's, and a policy that prices gear by slot asks konfer:TokenEquipLoc.
--
-- Drawn from RCLootCouncil's token table and, for Zul'Gurub and Ahn'Qiraj which it lacks, from the gear Gargul links each
-- token to, and checked against those links wherever both have a token. The names are the tokens', for the reader.
